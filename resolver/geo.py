    "хорваті", "croatia", "кіпр", "cyprus", "чехі", "чеськ", "czechia", "czech",
    "дані", "denmark", "естоні", "estonia", "фінлянді", "finland",
    "франці", "france", "німеччин", "germany", "греці", "еллад", "greece",
    "угорщин", "hungary", "ірланді", "ireland", "італі", "italy",
    "латві", "latvia", "литв", "lithuania", "люксембург", "luxembourg",
    "мальт", "malta", "нідерланд", "голланді", "netherlands", "holland",
