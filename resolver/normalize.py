"""
Нормализация текста. Только стандартная библиотека: ни морфологического
анализатора, ни весов моделей — их пришлось бы качать, а репозиторий должен
разворачиваться одной командой на чужой машине.

Три инструмента, каждый закрывает свой класс расхождений:

  stem()        — падежи и числа: «мериносу» → «меринос», «палиці» → «палиц».
                  Правила, а не словарь: словарь украинской морфологии весит
                  десятки мегабайт, а нам нужно лишь отрезать окончание.

  translit()    — заимствования: «трекінгові» → «trekingovi» ≈ trekking,
                  «софтшел» → «softshel» ≈ softshell. Работает на словах,
                  которых нет в таблице форм, — то есть на их файле вопросов.

  similar()     — опечатки и неточные формы, поверх первых двух.
"""

from __future__ import annotations

import re
import unicodedata
from difflib import SequenceMatcher

# Окончания украинского и русского, от длинных к коротким. Отрезаем не больше
# одного: «зворотню» → «зворотн», но «меринос» трогать нечего.
SUFFIXES = (
    "ами", "ями", "ові", "еві", "ією", "ому", "ему", "ого", "ої", "ий", "ій",
    "их", "іх", "им", "ім", "ах", "ях", "ам", "ям", "ів", "ою", "ею", "ов",
    "а", "е", "и", "і", "о", "у", "ю", "я", "й", "ь",
)
MIN_STEM = 4  # короче — уже не слово, а огрызок

_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "ґ": "g", "д": "d", "е": "e",
    "є": "ie", "ж": "zh", "з": "z", "и": "y", "і": "i", "ї": "i", "й": "i",
    "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch",
    "ш": "sh", "щ": "shch", "ь": "", "ю": "iu", "я": "ia", "ъ": "", "ы": "y",
    "э": "e", "ё": "e",
}
# г передаём как g, а не как h: цель — совпасть с английскими заимствованиями
# (trekking, gloves), а не соблюсти паспортный стандарт транслитерации.

_WORD = re.compile(r"[0-9a-zа-яіїєґёA-ZА-ЯІЇЄҐЁ]+(?:-[0-9a-zа-яіїєґёA-ZА-ЯІЇЄҐЁ]+)*")


def normalize(text: str) -> str:
    """Регистр, юникодные варианты букв, апострофы."""
    text = unicodedata.normalize("NFKC", text).lower()
    return text.replace("’", "").replace("'", "").replace("ʼ", "")


def words(text: str) -> list[str]:
    return _WORD.findall(normalize(text))


def stem(word: str) -> str:
    """Отрезаем одно окончание, если после этого остаётся осмысленный корень."""
    for suf in SUFFIXES:
        if word.endswith(suf) and len(word) - len(suf) >= MIN_STEM:
            return word[: -len(suf)]
    return word


def translit(word: str) -> str:
    """Кириллица → латиница. Латинские слова проходят насквозь."""
    return "".join(_TRANSLIT.get(ch, ch) for ch in word)


def similar(a: str, b: str) -> float:
    """
    Близость двух слов от 0 до 1. Помимо расстояния учитываем вложенность:
    «кросів» и «кросівк» — одно и то же слово в разных формах, но обычное
    посимвольное сравнение штрафует их за разную длину.
    """
    if a == b:
        return 1.0
    # Префикс считаем той же основой, только если отброшено не больше четырёх
    # букв: «беж»/«бежев» — это словоформа, а «від»/«відправляєт» — разные слова.
    if (len(a) >= 3 and len(b) >= 3 and abs(len(a) - len(b)) <= 4
            and (a.startswith(b) or b.startswith(a))):
        return 0.95 if min(len(a), len(b)) >= 5 else 0.9
    # Перестановка соседних букв — самая частая опечатка при наборе, и она
    # сохраняет набор букв целиком: «трек»/«терк», «літр»/«ілтр», «светр»/«севтр».
    # Посимвольное сравнение штрафует такие пары до 0,75-0,80, хотя это одно
    # и то же слово. Порог длины 4, а не 5: основы после отсечения окончаний
    # короткие, и на пяти буквах правило не поймало бы «терк» и «куид».
    # Оценка 0,9 подобрана так, чтобы правило проходило порог совпадения,
    # но никогда не побеждало точное (1,0) и префиксное (0,95).
    if len(a) >= 4 and len(a) == len(b) and sorted(a) == sorted(b):
        return 0.9
    return SequenceMatcher(None, a, b).ratio()


def key(word: str) -> str:
    """Каноническая форма слова для словаря: нормализация + отсечение окончания."""
    return stem(normalize(word))
